export function generateTrackingNumber() {
  const prefixes = ["LGX", "LGS", "NG", "LOS", "ABJ", "PHC"]
  const prefix = prefixes[Math.floor(Math.random() * prefixes.length)]
  const n = Math.floor(1000000 + Math.random() * 9000000)
  return `${prefix}${n}`
}

export function estimateCost(weightKg: number, method: string, international: boolean) {
  const base = international ? 42000 : 12000
  const methodMul = method === "Priority" ? 2.1 : method === "Express" ? 1.6 : method === "Freight" ? 1.15 : 1
  return Math.round((base + weightKg * 3800) * methodMul)
}
